import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {join,resolve} from 'node:path';
import assert from 'node:assert/strict';
import {AlgorithmTools} from '../dist/src/algorithm_tools.js';
import {Events} from '../dist/src/events.js';
const root=resolve(import.meta.dirname,'..'),out=join(root,'runs/smoke-v6-tool-checkpoint');mkdirSync(out,{recursive:true});
const sc=JSON.parse(readFileSync(join(root,'configs/orders20.json'),'utf8'));
sc.transport.vehicle_count=1;
sc.orders=[{id:'A',route:'R',release_minutes:0,due_minutes:5760}];
sc.routes=[{id:'R',operations:[{fire:1,temp:1150,hold_min:60,hold_max:180,forge:10}]}];
writeFileSync(join(out,'scenario.json'),JSON.stringify(sc));
const source='def construct():\n saved=restore()\n state=saved["state"] if saved else root()\n if complete(state):return state\n choices=candidates(state)\n if not choices:return None\n state=advance(state,choices[0]["id"])\n checkpoint({"state":state})\n return state if complete(state) else None\n';
const t=new AlgorithmTools(root,out,join(root,'.venv/bin/python'),sc,'none',new Events(join(out,'events.jsonl'),'check',performance.now()));
const signal=new AbortController().signal;
const first=await t.execute('run_algorithm',{source,seconds:2},signal);assert.equal(first.valid,false);
const second=await t.execute('run_algorithm',{source,seconds:2,resume_trial_id:first.trial_id},signal);assert.equal(second.audit_valid,true,JSON.stringify(second));
const third=await t.execute('run_algorithm',{source,seconds:2,resume_trial_id:second.trial_id},signal);assert.equal(third.audit_valid,true,JSON.stringify(third));
const report={controller_restored:true,complete:true,third_resume_valid:true,first_trial:first.trial_id,second_trial:second.trial_id,third_trial:third.trial_id};
writeFileSync(join(out,'summary.json'),JSON.stringify(report,null,2));console.log(JSON.stringify(report));
